test("labels from 1.0.4 are unchanged", () => {
    const current = new Set<string>();
    for (const group of CATEGORIES) {
        for (const name of group.names) {
            current.add(`${group.source}:${name}`);
        }
    }
    for (const [key, title] of Object.entries(LABELS_1_0_4)) {
        const name = key.slice(key.indexOf(":") + 1);
        assert.ok(current.has(key), `${key} is missing from CATEGORIES`);
        assert.equal(titleFor(name), title, key);
    }
});
